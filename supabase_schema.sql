-- 1) الصفوف
create table if not exists public.classes (
    name text primary key
);

-- 2) الطلاب: صف واحد لكل صورة (يدعم عدة صور لنفس الطالب)
create table if not exists public.students (
    id          bigint generated by default as identity primary key,
    name        text not null,
    class_name  text,
    student_id  text,
    photo       text,
    feature     text,
    created_at  timestamptz not null default now(),
    unique (name, class_name, photo)
);

-- إن كانت الجداول موجودة مسبقاً، أضف العمود الجديد فقط:
-- alter table public.students add column if not exists student_id text;
-- alter table public.students add column if not exists photo text;
-- alter table public.students add column if not exists feature text;

create index if not exists students_name_idx on public.students (name);
create index if not exists students_class_idx on public.students (class_name);

-- 3) الحضور: سجل واحد لكل طالب في اليوم
create table if not exists public.attendance (
    id           bigint generated by default as identity primary key,
    student_name text not null,
    date         date not null,
    time         text,
    unique (student_name, date)
);

create index if not exists attendance_date_idx on public.attendance (date);

